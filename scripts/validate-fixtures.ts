/**
 * Checks eval/fixtures/ and reports what the set covers.
 *
 * Run with `npm run fixtures:check`. Node executes this TypeScript directly by stripping
 * types, which is why src/core/ imports carry a .ts extension: the same modules the
 * extension bundles are the ones measuring the fixtures here, so the numbers in this table
 * are the numbers the pacing engine will see.
 *
 * The fixtures are the whole basis for every later phase, so this fails loudly on a
 * malformed one rather than letting a bad file quietly skew results months from now.
 */

import { readdir, readFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { computeTranscriptStats, formatDuration } from '../src/core/stats.ts';
import type { Transcript } from '../src/core/types.ts';
import type { TranscriptStats } from '../src/core/stats.ts';

const fixturesDir = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'eval', 'fixtures');

/** The five properties the spec asks the fixture set to cover between them. */
const REQUIREMENTS = [
  {
    name: 'Manual captions, 30 min or longer',
    test: (t: Transcript, s: TranscriptStats) => !t.isAutoGenerated && s.durationSec >= 1800,
  },
  {
    name: 'Auto-generated captions',
    test: (t: Transcript) => t.isAutoGenerated,
  },
  {
    name: 'Chapter markers present',
    test: (_t: Transcript, s: TranscriptStats) => s.chapterCount > 0,
  },
  {
    name: 'Fast talker, above 190 wpm',
    test: (_t: Transcript, s: TranscriptStats) => s.avgWpm > 190,
  },
  {
    name: 'Slow talker, above 8 percent silence',
    test: (_t: Transcript, s: TranscriptStats) => s.silencePct > 8,
  },
];

function validateShape(transcript: unknown, file: string): string[] {
  const problems: string[] = [];
  const t = transcript as Partial<Transcript>;

  if (typeof t.videoId !== 'string' || !t.videoId) problems.push('missing videoId');
  if (typeof t.language !== 'string') problems.push('missing language');
  if (typeof t.isAutoGenerated !== 'boolean') problems.push('missing isAutoGenerated');
  if (t.source !== 'captions' && t.source !== 'manual') problems.push('missing or invalid source');
  if (t.wordTimingSource !== 'native' && t.wordTimingSource !== 'interpolated') {
    problems.push('missing or invalid wordTimingSource');
  }
  if (typeof t.durationSec !== 'number' || !Number.isFinite(t.durationSec) || t.durationSec <= 0) {
    problems.push('missing or invalid durationSec');
  }
  if (!Array.isArray(t.cues) || t.cues.length === 0) {
    problems.push('no cues');
    return problems.map((problem) => `${file}: ${problem}`);
  }

  let previousEnd = -Infinity;
  for (const [i, cue] of t.cues.entries()) {
    const where = `cue ${i}`;
    if (typeof cue.text !== 'string' || cue.text.trim() === '') problems.push(`${where} has no text`);
    if (!Number.isFinite(cue.start) || !Number.isFinite(cue.end)) {
      problems.push(`${where} has non-finite timing`);
      continue;
    }
    if (cue.end <= cue.start) problems.push(`${where} ends before it starts`);
    if (cue.start < previousEnd - 1e-6) problems.push(`${where} overlaps the previous cue`);
    previousEnd = cue.end;

    for (const word of cue.words ?? []) {
      if (word.start < cue.start - 1e-6 || word.end > cue.end + 1e-6) {
        problems.push(`${where} has a word outside the cue bounds`);
        break;
      }
    }
  }

  const lastEnd = t.cues[t.cues.length - 1]?.end ?? 0;
  if (typeof t.durationSec === 'number' && lastEnd > t.durationSec + 1e-6) {
    problems.push('last cue ends after durationSec');
  }

  return problems.map((problem) => `${file}: ${problem}`);
}

function markdownTable(rows: string[][]): string {
  const widths = rows[0]!.map((_, column) =>
    Math.max(...rows.map((row) => row[column]!.length)),
  );
  const render = (row: string[]) =>
    `| ${row.map((cell, i) => cell.padEnd(widths[i]!)).join(' | ')} |`;

  return [
    render(rows[0]!),
    `| ${widths.map((width) => '-'.repeat(width)).join(' | ')} |`,
    ...rows.slice(1).map(render),
  ].join('\n');
}

async function main(): Promise<void> {
  let files: string[];
  try {
    files = (await readdir(fixturesDir)).filter((name) => name.endsWith('.json')).sort();
  } catch {
    console.error(`No fixtures directory at ${fixturesDir}`);
    process.exit(1);
  }

  if (files.length === 0) {
    console.error('No fixtures found. Capture them with the dev panel on a watch page.');
    process.exit(1);
  }

  const problems: string[] = [];
  const loaded: Array<{ file: string; transcript: Transcript; stats: TranscriptStats }> = [];

  for (const file of files) {
    let parsed: unknown;
    try {
      parsed = JSON.parse(await readFile(join(fixturesDir, file), 'utf8'));
    } catch (error) {
      problems.push(`${file}: not valid JSON (${String(error)})`);
      continue;
    }

    const shapeProblems = validateShape(parsed, file);
    if (shapeProblems.length > 0) {
      problems.push(...shapeProblems);
      continue;
    }

    const transcript = parsed as Transcript;
    loaded.push({ file, transcript, stats: computeTranscriptStats(transcript) });
  }

  if (loaded.length > 0) {
    const rows = [
      ['fixture', 'video', 'length', 'captions', 'timings', 'cues', 'words', 'wpm', 'silence', 'chapters'],
      ...loaded.map(({ file, transcript, stats }) => [
        file.replace(/\.json$/, ''),
        transcript.videoId,
        formatDuration(stats.durationSec),
        transcript.isAutoGenerated ? 'auto' : 'manual',
        transcript.wordTimingSource,
        String(stats.cueCount),
        String(stats.wordCount),
        stats.avgWpm.toFixed(0),
        `${stats.silencePct.toFixed(1)}%`,
        String(stats.chapterCount),
      ]),
    ];
    console.log(`\n${markdownTable(rows)}\n`);
  }

  const uncovered: string[] = [];
  console.log('Coverage');
  for (const requirement of REQUIREMENTS) {
    const match = loaded.find(({ transcript, stats }) => requirement.test(transcript, stats));
    if (match) {
      console.log(`  ok    ${requirement.name}  (${match.file})`);
    } else {
      console.log(`  MISS  ${requirement.name}`);
      uncovered.push(requirement.name);
    }
  }

  // Word timings depend on what YouTube serves, so this is worth knowing about but is not
  // grounds for failing the check.
  const interpolatedManual = loaded.filter(
    ({ transcript }) =>
      transcript.source === 'captions' &&
      !transcript.isAutoGenerated &&
      transcript.wordTimingSource === 'interpolated',
  );
  if (interpolatedManual.length > 0) {
    console.log('\nNote: manual-caption fixtures without native word timings:');
    for (const { file } of interpolatedManual) console.log(`  ${file}`);
  }

  if (problems.length > 0) {
    console.error('\nProblems');
    for (const problem of problems) console.error(`  ${problem}`);
  }

  if (problems.length > 0 || uncovered.length > 0) {
    console.error(
      `\nFailed: ${problems.length} malformed fixture(s), ${uncovered.length} uncovered requirement(s).`,
    );
    process.exit(1);
  }

  console.log(`\nAll ${loaded.length} fixtures valid and all requirements covered.`);
}

await main();
