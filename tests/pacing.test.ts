import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { buildChunks } from '../src/core/chunking.ts';
import { computeSpeedPlan } from '../src/core/pacing.ts';
import { DEFAULTS } from '../src/core/types.ts';
import type { Chunk, DifficultyScore, Settings, Transcript } from '../src/core/types.ts';
import { makeTranscript, silenceChunk, speechChunk, uniformChunks } from './support/transcripts.ts';

const fixturesDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'eval', 'fixtures');

function loadFixture(name: string): Transcript {
  return JSON.parse(readFileSync(join(fixturesDir, name), 'utf8')) as Transcript;
}

/** A transcript carrying only the fields the planner reads, for hand-built chunk lists. */
function shell(durationSec: number, chapters?: Transcript['chapters']): Transcript {
  const transcript: Transcript = {
    videoId: 'synthetic',
    language: 'en',
    isAutoGenerated: false,
    durationSec,
    cues: [],
    wordTimingSource: 'interpolated',
    source: 'captions',
  };
  if (chapters) transcript.chapters = chapters;
  return transcript;
}

function settings(overrides: Partial<Settings> = {}): Settings {
  return { ...DEFAULTS, ...overrides };
}

function endOf(chunks: Chunk[]): number {
  return chunks[chunks.length - 1]!.end;
}

describe('the control law', () => {
  it('holds one speed across a transcript with a constant speech rate', () => {
    // Nothing varies, so nothing should move. If smoothing or consolidation had a bias this
    // is where it would show up as drift.
    const chunks = uniformChunks(12, 30, 150);
    const plan = computeSpeedPlan(shell(endOf(chunks)), chunks, null, settings());

    const speeds = new Set(plan.segments.map((segment) => segment.speed));
    expect(speeds.size).toBe(1);
  });

  it('halves the speed for a speaker going at twice the target rate', () => {
    // ln(s) = ln(R) - ln(r) with r = 2R gives exactly 0.5. Chosen so both R and r sit inside
    // the [90, 260] clamp, and with a min speed low enough not to interfere.
    const chunks = uniformChunks(10, 30, 240);
    const plan = computeSpeedPlan(
      shell(endOf(chunks)),
      chunks,
      null,
      settings({ targetWpm: 120, minSpeed: 0.25 }),
    );

    expect(plan.segments[0]!.speed).toBeCloseTo(0.5, 6);
  });

  it('slows for a difficult passage and speeds up for an easy one', () => {
    const chunks = uniformChunks(8, 30, 150);
    const scores: DifficultyScore[] = chunks.map((chunk, i) => ({
      chunkId: chunk.id,
      raw: 5,
      z: i < 4 ? 1 : -1,
      imputed: false,
    }));

    const plan = computeSpeedPlan(
      shell(endOf(chunks)),
      chunks,
      scores,
      settings({ alpha: 0.4, smoothingWindowSec: 0 }),
    );

    const first = plan.segments[0]!;
    const last = plan.segments[plan.segments.length - 1]!;
    expect(first.speed).toBeLessThan(last.speed);
  });
});

describe('guardrails', () => {
  it('does not let a near-silent chunk demand an absurd speed', () => {
    // Four words over nine seconds reads as 27 wpm, which without the input clamp would ask
    // for eight times speed.
    const chunks = [speechChunk(0, 0, 9, 4)];
    const plan = computeSpeedPlan(shell(9), chunks, null, settings());

    expect(plan.segments[0]!.speed).toBeLessThanOrEqual(DEFAULTS.maxSpeed);
    expect(plan.segments[0]!.speed).toBeGreaterThanOrEqual(DEFAULTS.minSpeed);
  });

  it('keeps every speed inside the range and on the step grid', () => {
    const transcript = loadFixture('manual-lecture-J7DzL2_Na80.json');
    const plan = computeSpeedPlan(
      transcript,
      buildChunks(transcript, DEFAULTS),
      null,
      DEFAULTS,
    );

    for (const segment of plan.segments) {
      expect(segment.speed).toBeGreaterThanOrEqual(DEFAULTS.minSpeed - 1e-9);
      // maxSpeed governs speech only. Silence is deliberately allowed past it, because the
      // limit exists for intelligibility and a pause has nothing to be unintelligible.
      const ceiling = segment.kind === 'silence' ? DEFAULTS.silenceSpeed : DEFAULTS.maxSpeed;
      expect(segment.speed).toBeLessThanOrEqual(ceiling + 1e-9);
      const steps = segment.speed / DEFAULTS.speedStep;
      expect(Math.abs(steps - Math.round(steps))).toBeLessThan(1e-6);
    }
  });

  it('holds every speech segment for at least the dwell time', () => {
    // Rates alternate hard enough to want a change at every chunk. The dwell rule has to
    // absorb the short ones, because a correct speed held for two seconds is worse than a
    // slightly wrong one held long enough to settle.
    const chunks = Array.from({ length: 24 }, (_, i) =>
      speechChunk(i, i * 5, (i + 1) * 5, i % 2 === 0 ? 10 : 20),
    );
    const plan = computeSpeedPlan(shell(endOf(chunks)), chunks, null, settings());

    for (const segment of plan.segments) {
      if (segment.kind !== 'speech') continue;
      expect(segment.end - segment.start).toBeGreaterThanOrEqual(DEFAULTS.minDwellSec - 1e-6);
    }
  });

  it('exempts silence from the dwell rule', () => {
    // A three second pause at triple speed is the single most valuable thing here, and the
    // dwell rule would otherwise dissolve every one of them.
    const chunks: Chunk[] = [
      speechChunk(0, 0, 30, 75),
      silenceChunk(1, 30, 33),
      speechChunk(2, 33, 63, 75),
    ];
    const plan = computeSpeedPlan(shell(63), chunks, null, settings());

    const silence = plan.segments.filter((segment) => segment.kind === 'silence');
    expect(silence).toHaveLength(1);
    expect(silence[0]!.speed).toBeCloseTo(DEFAULTS.silenceSpeed, 6);
    expect(silence[0]!.end - silence[0]!.start).toBeCloseTo(3, 6);
  });
});

describe('segment geometry', () => {
  it('emits contiguous segments covering the whole video', () => {
    const transcript = loadFixture('chapters-silence-lUUte2o2Sn8.json');
    const plan = computeSpeedPlan(
      transcript,
      buildChunks(transcript, DEFAULTS),
      null,
      DEFAULTS,
    );

    expect(plan.segments[0]!.start).toBe(0);
    expect(plan.segments[plan.segments.length - 1]!.end).toBeCloseTo(transcript.durationSec, 6);

    plan.segments.forEach((segment, i) => {
      expect(segment.end).toBeGreaterThan(segment.start);
      if (i > 0) expect(segment.start).toBeCloseTo(plan.segments[i - 1]!.end, 6);
    });
  });

  it('reports a watch time shorter than the original when speeding up', () => {
    const transcript = loadFixture('manual-lecture-J7DzL2_Na80.json');
    const plan = computeSpeedPlan(
      transcript,
      buildChunks(transcript, DEFAULTS),
      null,
      DEFAULTS,
    );

    expect(plan.meta.estimatedWatchTimeSec).toBeLessThan(plan.meta.originalDurationSec);
    expect(plan.meta.estimatedWatchTimeSec).toBeGreaterThan(0);
  });
});

describe('smoothing', () => {
  it('reduces whiplash as the window widens', () => {
    // Measured on a real transcript, with a fine speed step so the result is not dominated
    // by quantization, and no dwell merging so smoothing is the only thing acting.
    const transcript = loadFixture('manual-lecture-J7DzL2_Na80.json');
    const chunks = buildChunks(transcript, DEFAULTS);

    const whiplash = [0, 10, 20, 40, 80].map(
      (smoothingWindowSec) =>
        computeSpeedPlan(
          transcript,
          chunks,
          null,
          settings({ smoothingWindowSec, minDwellSec: 0, speedStep: 0.001 }),
        ).meta.whiplash,
    );

    for (let i = 1; i < whiplash.length; i += 1) {
      expect(whiplash[i]!).toBeLessThanOrEqual(whiplash[i - 1]! + 1e-9);
    }
  });

  it('does not carry pace across a chapter boundary', () => {
    // Two chapters, each internally uniform but very different from each other. With the
    // chapter gate the speeds stay flat right up to the boundary. Without it, the chunks on
    // either side would be pulled toward each other.
    const chapters = [
      { title: 'One', start: 0 },
      { title: 'Two', start: 300 },
    ];
    const slow = uniformChunks(10, 30, 150);
    const fast = uniformChunks(10, 30, 250).map((chunk, i) => ({
      ...chunk,
      id: 10 + i,
      start: 300 + i * 30,
      end: 300 + (i + 1) * 30,
    }));
    const chunks = [...slow, ...fast];

    const plan = computeSpeedPlan(shell(600, chapters), chunks, null, settings());

    // Each chapter collapses to a single segment, and they are not the same speed.
    expect(plan.segments).toHaveLength(2);
    expect(plan.segments[0]!.end).toBeCloseTo(300, 6);
    expect(plan.segments[0]!.speed).toBeGreaterThan(plan.segments[1]!.speed);
  });
});

describe('policy selection', () => {
  it('uses the wpm policy when no scores are supplied', () => {
    const chunks = uniformChunks(6, 30, 150);
    const plan = computeSpeedPlan(shell(endOf(chunks)), chunks, null, settings());

    expect(plan.policy).toBe('wpm');
    expect(plan.segments.every((segment) => segment.difficultyZ === null)).toBe(true);
  });

  it('falls back to the wpm policy when alpha is zero, even with scores', () => {
    // alpha is the trust knob. Turning it to zero must ignore the model entirely rather than
    // multiplying its influence by zero and still calling the result LLM-driven.
    const chunks = uniformChunks(6, 30, 150);
    const scores: DifficultyScore[] = chunks.map((chunk) => ({
      chunkId: chunk.id,
      raw: 8,
      z: 2,
      imputed: false,
    }));

    const plan = computeSpeedPlan(
      shell(endOf(chunks)),
      chunks,
      scores,
      settings({ alpha: 0 }),
    );

    expect(plan.policy).toBe('wpm');
    expect(plan.segments.every((segment) => segment.difficultyZ === null)).toBe(true);
  });

  it('counts imputed scores in the metadata', () => {
    const chunks = uniformChunks(4, 30, 150);
    const scores: DifficultyScore[] = chunks.map((chunk, i) => ({
      chunkId: chunk.id,
      raw: 5,
      z: 0,
      imputed: i < 2,
    }));

    const plan = computeSpeedPlan(shell(endOf(chunks)), chunks, scores, settings());

    expect(plan.policy).toBe('wpm+llm');
    expect(plan.meta.scoresImputed).toBe(2);
  });

  it('treats a chunk with no score as average rather than failing', () => {
    const chunks = uniformChunks(6, 30, 150);
    const scores: DifficultyScore[] = [{ chunkId: 0, raw: 9, z: 1.5, imputed: false }];

    const plan = computeSpeedPlan(shell(endOf(chunks)), chunks, scores, settings());

    expect(plan.segments.every((segment) => Number.isFinite(segment.speed))).toBe(true);
  });
});

describe('degenerate input', () => {
  it('returns an empty plan for a transcript with no chunks', () => {
    const plan = computeSpeedPlan(shell(120), [], null, settings());

    expect(plan.segments).toEqual([]);
    expect(plan.meta.estimatedWatchTimeSec).toBe(0);
    expect(plan.meta.whiplash).toBe(0);
    expect(plan.meta.originalDurationSec).toBe(120);
  });
});

describe('fuzzing', () => {
  it('produces a valid plan for 500 random transcripts', () => {
    // Deterministic generator so a failure is reproducible rather than a one-off.
    let seed = 0x2f6e2b1;
    const random = () => {
      seed = (seed * 1103515245 + 12345) & 0x7fffffff;
      return seed / 0x7fffffff;
    };

    for (let run = 0; run < 500; run += 1) {
      const transcript = makeTranscript({
        cues: 1 + Math.floor(random() * 60),
        cueSec: 0.5 + random() * 8,
        wordsPerCue: Math.floor(random() * 25),
        gapSec: random() < 0.4 ? random() * 5 : 0,
        punctuate: random() < 0.5,
        isAutoGenerated: random() < 0.5,
      });

      const chunks = buildChunks(transcript, DEFAULTS);
      const plan = computeSpeedPlan(transcript, chunks, null, DEFAULTS);

      expect(Number.isFinite(plan.meta.estimatedWatchTimeSec)).toBe(true);
      expect(Number.isFinite(plan.meta.whiplash)).toBe(true);

      for (const segment of plan.segments) {
        expect(Number.isFinite(segment.speed)).toBe(true);
        expect(segment.speed).toBeGreaterThanOrEqual(DEFAULTS.minSpeed - 1e-9);
        const ceiling = segment.kind === 'silence' ? DEFAULTS.silenceSpeed : DEFAULTS.maxSpeed;
        expect(segment.speed).toBeLessThanOrEqual(ceiling + 1e-9);
        expect(Number.isFinite(segment.start)).toBe(true);
        expect(Number.isFinite(segment.end)).toBe(true);
        expect(segment.end).toBeGreaterThan(segment.start);
      }

      if (plan.segments.length > 0) {
        expect(plan.segments[0]!.start).toBe(0);
        expect(plan.segments[plan.segments.length - 1]!.end).toBeCloseTo(
          transcript.durationSec,
          6,
        );
      }
    }
  });
});
