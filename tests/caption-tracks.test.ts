import { describe, expect, it } from 'vitest';
import {
  extractChapters,
  getCaptionTracks,
  getVideoDetails,
  isAutoGenerated,
  selectCaptionTrack,
  withCaptionFormat,
  withProofOfOrigin,
} from '../src/core/caption-tracks.ts';
import type { CaptionTrack } from '../src/core/caption-tracks.ts';

function track(languageCode: string, kind?: string): CaptionTrack {
  return kind === undefined
    ? { baseUrl: `https://timedtext/${languageCode}`, languageCode }
    : { baseUrl: `https://timedtext/${languageCode}`, languageCode, kind };
}

describe('getCaptionTracks', () => {
  it('reads the track list out of a player response', () => {
    const playerResponse = {
      captions: {
        playerCaptionsTracklistRenderer: {
          captionTracks: [
            { baseUrl: 'https://a', languageCode: 'en', kind: 'asr', vssId: 'a.en' },
            { baseUrl: 'https://b', languageCode: 'de' },
          ],
        },
      },
    };

    expect(getCaptionTracks(playerResponse)).toEqual([
      { baseUrl: 'https://a', languageCode: 'en', kind: 'asr', vssId: 'a.en' },
      { baseUrl: 'https://b', languageCode: 'de' },
    ]);
  });

  it('returns an empty list for a video with no captions', () => {
    expect(getCaptionTracks({ captions: {} })).toEqual([]);
    expect(getCaptionTracks({})).toEqual([]);
    expect(getCaptionTracks(null)).toEqual([]);
  });

  it('drops entries with no usable baseUrl', () => {
    const playerResponse = {
      captions: {
        playerCaptionsTracklistRenderer: {
          captionTracks: [{ languageCode: 'en' }, { baseUrl: '', languageCode: 'en' }],
        },
      },
    };

    expect(getCaptionTracks(playerResponse)).toEqual([]);
  });
});

describe('isAutoGenerated', () => {
  it('recognises both the kind field and the vssId prefix', () => {
    expect(isAutoGenerated(track('en', 'asr'))).toBe(true);
    expect(isAutoGenerated({ baseUrl: 'x', languageCode: 'en', vssId: 'a.en' })).toBe(true);
    expect(isAutoGenerated(track('en'))).toBe(false);
  });
});

describe('selectCaptionTrack', () => {
  it('prefers a manual track in the preferred language', () => {
    const tracks = [track('en', 'asr'), track('de'), track('en')];
    expect(selectCaptionTrack(tracks, ['en'])?.languageCode).toBe('en');
    expect(selectCaptionTrack(tracks, ['en'])?.kind).toBeUndefined();
  });

  it('prefers any manual track over an auto-generated one in the right language', () => {
    const tracks = [track('en', 'asr'), track('de')];
    expect(selectCaptionTrack(tracks, ['en'])?.languageCode).toBe('de');
  });

  it('falls back to auto-generated when nothing manual exists', () => {
    const tracks = [track('fr', 'asr'), track('en', 'asr')];
    expect(selectCaptionTrack(tracks, ['en'])?.languageCode).toBe('en');
  });

  it('treats a regional variant as a match for the base language', () => {
    const tracks = [track('de'), track('en-GB')];
    expect(selectCaptionTrack(tracks, ['en-US'])?.languageCode).toBe('en-GB');
  });

  it('prefers an exact match over a base-language match', () => {
    const tracks = [track('en-GB'), track('en-US')];
    expect(selectCaptionTrack(tracks, ['en-US'])?.languageCode).toBe('en-US');
  });

  it('returns null for an empty list', () => {
    expect(selectCaptionTrack([], ['en'])).toBeNull();
  });
});

describe('withCaptionFormat', () => {
  // The signed URL must survive byte for byte. Re-encoding the commas in sparams breaks
  // the signature, YouTube returns an empty body, and the video looks caption-less.
  const signed =
    'https://www.youtube.com/api/timedtext?v=abc&ei=x-Y&caps=asr&sparams=ip,ipbits,expire,v,caps&signature=A1B2%2FC3&key=yt8&lang=en';

  it('leaves the signed query string untouched', () => {
    const result = withCaptionFormat(signed, 'json3');

    expect(result).toBe(`${signed}&fmt=json3`);
    expect(result).toContain('sparams=ip,ipbits,expire,v,caps');
    expect(result).toContain('signature=A1B2%2FC3');
  });

  it('replaces an existing fmt rather than adding a second one', () => {
    const withSrv3 = `${signed}&fmt=srv3`;
    const result = withCaptionFormat(withSrv3, 'json3');

    expect(result.match(/fmt=/g)).toHaveLength(1);
    expect(result).toContain('fmt=json3');
    expect(result).toContain('sparams=ip,ipbits,expire,v,caps');
  });

  it('strips fmt entirely when asked for the default format', () => {
    expect(withCaptionFormat(`${signed}&fmt=json3`, null)).toBe(signed);
  });

  it('handles fmt appearing as the first parameter', () => {
    expect(withCaptionFormat('https://host/path?fmt=srv3&v=abc', 'json3')).toBe(
      'https://host/path?v=abc&fmt=json3',
    );
    expect(withCaptionFormat('https://host/path?fmt=srv3', null)).toBe('https://host/path');
  });

  it('adds a query string when the url has none', () => {
    expect(withCaptionFormat('https://host/path', 'json3')).toBe('https://host/path?fmt=json3');
  });
});

describe('withProofOfOrigin', () => {
  const signed =
    'https://www.youtube.com/api/timedtext?v=abc&sparams=ip,ipbits,expire&signature=A1B2%2FC3&lang=en&fmt=json3';

  it('appends the client tag and the token together', () => {
    // YouTube returns an empty 200 unless both are present, so they are added as a pair.
    expect(withProofOfOrigin(signed, 'TOKEN123')).toBe(`${signed}&c=WEB&pot=TOKEN123`);
  });

  it('leaves the signed query string untouched', () => {
    const result = withProofOfOrigin(signed, 'TOKEN123');

    expect(result).toContain('sparams=ip,ipbits,expire');
    expect(result).toContain('signature=A1B2%2FC3');
  });

  it('encodes a token containing url-significant characters', () => {
    expect(withProofOfOrigin(signed, 'a+b/c=d')).toContain('pot=a%2Bb%2Fc%3Dd');
  });

  it('returns the url unchanged when no token was obtained', () => {
    expect(withProofOfOrigin(signed, null)).toBe(signed);
    expect(withProofOfOrigin(signed, '')).toBe(signed);
  });

  it('starts a query string when the url has none', () => {
    expect(withProofOfOrigin('https://host/path', 'T')).toBe('https://host/path?c=WEB&pot=T');
  });
});

describe('getVideoDetails', () => {
  it('parses the string lengthSeconds YouTube sends', () => {
    expect(getVideoDetails({ videoDetails: { videoId: 'abc', lengthSeconds: '3600' } })).toEqual({
      videoId: 'abc',
      durationSec: 3600,
    });
  });

  it('returns nulls rather than throwing on junk', () => {
    expect(getVideoDetails(null)).toEqual({ videoId: null, durationSec: null });
    expect(getVideoDetails({ videoDetails: { lengthSeconds: 'nope' } })).toEqual({
      videoId: null,
      durationSec: null,
    });
  });
});

describe('extractChapters', () => {
  const markersMap = [
    {
      key: 'DESCRIPTION_CHAPTERS',
      value: {
        chapters: [
          { chapterRenderer: { title: { simpleText: 'Intro' }, timeRangeStartMillis: 0 } },
          { chapterRenderer: { title: { simpleText: 'Proof' }, timeRangeStartMillis: 95000 } },
        ],
      },
    },
  ];

  it('reads chapters from the known player bar path', () => {
    const data = {
      playerOverlays: {
        playerOverlayRenderer: {
          decoratedPlayerBarRenderer: {
            decoratedPlayerBarRenderer: {
              playerBar: { multiMarkersPlayerBarRenderer: { markersMap } },
            },
          },
        },
      },
    };

    expect(extractChapters(data)).toEqual([
      { title: 'Intro', start: 0 },
      { title: 'Proof', start: 95 },
    ]);
  });

  it('finds a relocated markersMap by key', () => {
    expect(extractChapters({ somewhere: { unexpected: { markersMap } } })).toEqual([
      { title: 'Intro', start: 0 },
      { title: 'Proof', start: 95 },
    ]);
  });

  it('falls back to the macro markers panel', () => {
    const data = {
      engagementPanels: [
        {
          engagementPanelSectionListRenderer: {
            content: {
              macroMarkersListRenderer: {
                contents: [
                  {
                    macroMarkersListItemRenderer: {
                      title: { simpleText: 'Setup' },
                      onTap: { watchEndpoint: { startTimeSeconds: 12 } },
                    },
                  },
                ],
              },
            },
          },
        },
      ],
    };

    expect(extractChapters(data)).toEqual([{ title: 'Setup', start: 12 }]);
  });

  it('reads run-based titles', () => {
    const runs = [
      {
        key: 'AUTO_CHAPTERS',
        value: {
          chapters: [
            {
              chapterRenderer: {
                title: { runs: [{ text: 'Part ' }, { text: 'one' }] },
                timeRangeStartMillis: 1000,
              },
            },
          ],
        },
      },
    ];

    expect(extractChapters({ markersMap: runs })).toEqual([{ title: 'Part one', start: 1 }]);
  });

  it('sorts and deduplicates by start time', () => {
    const unsorted = [
      {
        key: 'DESCRIPTION_CHAPTERS',
        value: {
          chapters: [
            { chapterRenderer: { title: { simpleText: 'B' }, timeRangeStartMillis: 20000 } },
            { chapterRenderer: { title: { simpleText: 'A' }, timeRangeStartMillis: 0 } },
            { chapterRenderer: { title: { simpleText: 'A duplicate' }, timeRangeStartMillis: 0 } },
          ],
        },
      },
    ];

    expect(extractChapters({ markersMap: unsorted })).toEqual([
      { title: 'A', start: 0 },
      { title: 'B', start: 20 },
    ]);
  });

  it('returns undefined for a video with no chapters, without throwing', () => {
    expect(extractChapters({})).toBeUndefined();
    expect(extractChapters(null)).toBeUndefined();
    expect(extractChapters('a string')).toBeUndefined();
    expect(extractChapters({ markersMap: [{ key: 'HEATSEEKER', value: {} }] })).toBeUndefined();
    expect(
      extractChapters({ markersMap: [{ value: { chapters: [{ chapterRenderer: {} }] } }] }),
    ).toBeUndefined();
  });
});
