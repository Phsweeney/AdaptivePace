/**
 * Builders for the synthetic transcripts and chunk lists the engine tests run against.
 *
 * Fixtures prove the engine survives real captions; these prove it does the right arithmetic.
 * A real transcript cannot answer "is the speed exactly half when the speaker is exactly
 * twice as fast", because no real speaker is exactly twice as fast as anything.
 */

import type { Chapter, Chunk, Transcript, TranscriptCue } from '../../src/core/types.ts';

export interface TranscriptOptions {
  /** Number of cues to emit. */
  cues?: number;
  /** Seconds of speech per cue. */
  cueSec?: number;
  /** Countable words per cue. Combined with cueSec this fixes the speech rate. */
  wordsPerCue?: number;
  /** Silent seconds inserted after every cue. */
  gapSec?: number;
  /** Whether cue text ends in a full stop, which is the only sentence-boundary signal. */
  punctuate?: boolean;
  chapters?: Chapter[];
  isAutoGenerated?: boolean;
  /** Defaults to the end of the last cue. */
  durationSec?: number;
}

/**
 * A transcript whose speech rate is exactly `60 * wordsPerCue / cueSec` everywhere.
 *
 * With `gapSec` at 0 the cues tile the timeline, so every chunk carries that same rate no
 * matter where the boundaries land. That is what makes "uniform input gives uniform speed"
 * a meaningful assertion rather than a coincidence of chunking.
 */
export function makeTranscript(options: TranscriptOptions = {}): Transcript {
  const {
    cues: cueCount = 40,
    cueSec = 3,
    wordsPerCue = 9,
    gapSec = 0,
    punctuate = true,
    chapters,
    isAutoGenerated = false,
    durationSec,
  } = options;

  const word = 'alpha';
  const body = Array.from({ length: wordsPerCue }, () => word).join(' ');
  const text = punctuate ? `${body}.` : body;

  const cues: TranscriptCue[] = [];
  for (let i = 0; i < cueCount; i += 1) {
    const start = i * (cueSec + gapSec);
    cues.push({ text, start, end: start + cueSec });
  }

  const lastEnd = cues.length > 0 ? cues[cues.length - 1]!.end : 0;
  const transcript: Transcript = {
    videoId: 'synthetic',
    language: 'en',
    isAutoGenerated,
    durationSec: durationSec ?? lastEnd,
    cues,
    wordTimingSource: 'interpolated',
    source: 'captions',
  };
  if (chapters) transcript.chapters = chapters;
  return transcript;
}

/** A speech chunk whose nativeWpm follows from its word count and span. */
export function speechChunk(id: number, start: number, end: number, wordCount: number): Chunk {
  const span = Math.max(end - start, 0);
  return {
    id,
    kind: 'speech',
    start,
    end,
    text: Array.from({ length: wordCount }, () => 'alpha').join(' '),
    wordCount,
    nativeWpm: span > 0 ? wordCount / (span / 60) : 0,
  };
}

export function silenceChunk(id: number, start: number, end: number): Chunk {
  return { id, kind: 'silence', start, end, text: '', wordCount: 0, nativeWpm: 0 };
}

/** Builds a run of equal-length speech chunks all at the same rate. */
export function uniformChunks(count: number, chunkSec: number, wpm: number): Chunk[] {
  const wordCount = Math.round(wpm * (chunkSec / 60));
  return Array.from({ length: count }, (_, i) =>
    speechChunk(i, i * chunkSec, (i + 1) * chunkSec, wordCount),
  );
}
