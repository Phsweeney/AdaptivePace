import { describe, expect, it } from 'vitest';
import { computeTranscriptStats, formatDuration } from '../src/core/stats.ts';
import type { Transcript } from '../src/core/types.ts';

function transcript(partial: Partial<Transcript>): Transcript {
  return {
    videoId: 'v1',
    language: 'en',
    isAutoGenerated: false,
    durationSec: 60,
    cues: [],
    wordTimingSource: 'native',
    source: 'captions',
    ...partial,
  };
}

describe('computeTranscriptStats', () => {
  it('measures speech rate against speaking time, not video length', () => {
    // 20 words spoken over 10 seconds inside a 60 second video is 120 wpm.
    const stats = computeTranscriptStats(
      transcript({
        durationSec: 60,
        cues: [{ text: Array.from({ length: 20 }, () => 'word').join(' '), start: 0, end: 10 }],
      }),
    );

    expect(stats.wordCount).toBe(20);
    expect(stats.speechSec).toBe(10);
    expect(stats.avgWpm).toBeCloseTo(120);
  });

  it('counts gaps at or above the silence threshold, including the run-out', () => {
    const stats = computeTranscriptStats(
      transcript({
        durationSec: 30,
        cues: [
          { text: 'one', start: 0, end: 5 },
          // A 1 second gap here is below the threshold and is not silence.
          { text: 'two', start: 6, end: 10 },
          // A 5 second gap here is.
          { text: 'three', start: 15, end: 20 },
        ],
      }),
    );

    expect(stats.silenceSec).toBe(15); // 5 second gap plus a 10 second run-out
    expect(stats.silencePct).toBeCloseTo(50);
  });

  it('reports zeroes for an empty transcript instead of NaN', () => {
    const stats = computeTranscriptStats(transcript({ durationSec: 0, cues: [] }));

    expect(stats.avgWpm).toBe(0);
    expect(stats.silencePct).toBe(0);
    expect(Number.isNaN(stats.avgWpm)).toBe(false);
  });

  it('reports chapter count and timing source', () => {
    const stats = computeTranscriptStats(
      transcript({ chapters: [{ title: 'Intro', start: 0 }], wordTimingSource: 'interpolated' }),
    );

    expect(stats.chapterCount).toBe(1);
    expect(stats.hasNativeWordTimings).toBe(false);
  });
});

describe('formatDuration', () => {
  it('drops the hour field below an hour', () => {
    expect(formatDuration(0)).toBe('0:00');
    expect(formatDuration(95)).toBe('1:35');
    expect(formatDuration(3661)).toBe('1:01:01');
  });
});
