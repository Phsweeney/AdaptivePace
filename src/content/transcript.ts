/**
 * Phase 0: turning a loaded watch page into a Transcript.
 *
 * Running on the page is the entire advantage. The caption track URLs in
 * ytInitialPlayerResponse are already signed for this session, and fetching them from the
 * page carries the cookies that signature expects. The same request made from a server is
 * routinely refused.
 *
 * Nothing here throws. A video without captions is an ordinary result, and the caller
 * shows the message from the returned failure.
 */

import {
  extractChapters,
  getCaptionTracks,
  getVideoDetails,
  isAutoGenerated,
  selectCaptionTrack,
  withCaptionFormat,
  withProofOfOrigin,
} from '../core/caption-tracks.ts';
import { parseJson3 } from '../core/parse-json3.ts';
import { parseTimedTextXml } from '../core/parse-srv3.ts';
import { transcriptFailure } from '../core/types.ts';
import type { ParsedCues } from '../core/parse-json3.ts';
import type { Transcript, TranscriptResult } from '../core/types.ts';
import { getPageData, getVideoIdFromUrl } from './page-data.ts';
import type { PageData } from './page-data.ts';
import { getProofOfOrigin } from './pot.ts';
import type { ProofOfOrigin } from './pot.ts';

/**
 * json3 first, because only it carries per-word timing offsets. The others are there so a
 * video whose json3 request is refused still produces a usable transcript.
 */
const FORMAT_LADDER = ['json3', 'srv3', null] as const;

/**
 * One caption fetch attempt. Kept because "no usable caption file" is the failure that can
 * end this project, and a bare message makes it impossible to tell a signature problem
 * from a blocked request from a parser bug.
 */
export interface FetchAttempt {
  fmt: string;
  status: number | string;
  bytes: number;
  /** First stretch of the response, for reading an error page or an empty reply. */
  preview: string;
  parsed: boolean;
}

export interface ExtractionDetails {
  /** Which page-data layer supplied the player response. */
  via: PageData['via'];
  /** Which timedtext format actually returned content. */
  format: 'json3' | 'srv3' | 'legacy' | null;
  trackName: string | null;
  /** Every caption track offered by the page, for spotting a bad selection. */
  availableTracks: string[];
  /** Where the proof-of-origin token came from. Without one every fetch returns empty. */
  pot: ProofOfOrigin['via'];
  attempts: FetchAttempt[];
}

export interface ExtractionSuccess {
  ok: true;
  transcript: Transcript;
  details: ExtractionDetails;
}

export interface ExtractionFailure {
  ok: false;
  reason: Extract<TranscriptResult, { ok: false }>['reason'];
  message: string;
  details: ExtractionDetails;
}

export type ExtractionResult = ExtractionSuccess | ExtractionFailure;

const NO_DETAILS: ExtractionDetails = {
  via: 'none',
  format: null,
  trackName: null,
  availableTracks: [],
  pot: 'unavailable',
  attempts: [],
};

function preferredLanguages(): string[] {
  const fromBrowser = typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : [];
  return [...fromBrowser.filter(Boolean), 'en'];
}

/** The player is the authority on duration. The last cue usually ends before the video does. */
export function getPlayerDuration(): number | null {
  const video = document.querySelector<HTMLVideoElement>('video.html5-main-video');
  const duration = video?.duration;
  return typeof duration === 'number' && Number.isFinite(duration) && duration > 0 ? duration : null;
}

async function fetchCaptionText(
  url: string,
): Promise<{ body: string | null; status: number | string }> {
  try {
    const response = await fetch(url, { credentials: 'include' });
    const body = await response.text();
    if (!response.ok) return { body: null, status: response.status };
    // An empty 200 is YouTube's way of declining. Treat it as a miss and try the next format.
    return { body: body.trim().length > 0 ? body : null, status: response.status };
  } catch (error) {
    return { body: null, status: error instanceof Error ? error.name : 'network-error' };
  }
}

async function fetchAndParse(
  baseUrl: string,
  pot: string | null,
  attempts: FetchAttempt[],
): Promise<{ parsed: ParsedCues; format: ExtractionDetails['format'] } | null> {
  for (const fmt of FORMAT_LADDER) {
    const label = fmt ?? 'default';
    const url = withProofOfOrigin(withCaptionFormat(baseUrl, fmt), pot);
    const { body, status } = await fetchCaptionText(url);

    if (body === null) {
      attempts.push({ fmt: label, status, bytes: 0, preview: '', parsed: false });
      continue;
    }

    const parsed = fmt === 'json3' ? parseJson3(body) : parseTimedTextXml(body);
    const usable = parsed !== null && parsed.cues.length > 0;
    attempts.push({
      fmt: label,
      status,
      bytes: body.length,
      preview: body.slice(0, 160),
      parsed: usable,
    });

    if (usable) {
      const format = fmt === 'json3' ? 'json3' : fmt === 'srv3' ? 'srv3' : 'legacy';
      return { parsed, format };
    }
  }

  return null;
}

export async function extractTranscript(requestedVideoId?: string): Promise<ExtractionResult> {
  const attempts: FetchAttempt[] = [];
  const fail = (
    reason: ExtractionFailure['reason'],
    message: string,
    partial: Partial<ExtractionDetails> = {},
  ): ExtractionFailure => ({
    ...transcriptFailure(reason, message),
    details: { ...NO_DETAILS, attempts, ...partial },
  });

  const videoId = requestedVideoId ?? getVideoIdFromUrl();
  if (!videoId) {
    return fail('not-a-watch-page', 'Open a YouTube watch page first.');
  }

  const pageData = await getPageData(videoId);
  if (pageData.playerResponse === null) {
    return fail('no-player-response', "Could not read this video's data from the page. Reloading usually fixes it.", {
      via: pageData.via,
    });
  }

  const tracks = getCaptionTracks(pageData.playerResponse);
  const availableTracks = tracks.map(
    (candidate) => `${candidate.languageCode}${isAutoGenerated(candidate) ? ' (auto)' : ''}`,
  );
  const track = selectCaptionTrack(tracks, preferredLanguages());
  if (track === null) {
    return fail('no-captions', 'No transcript available for this video.', {
      via: pageData.via,
      availableTracks,
    });
  }

  // Ordered after track selection so the token is minted for the track we are about to ask
  // for. It covers every track and format on the page, so one is fetched per extraction.
  const proof = await getProofOfOrigin(track.languageCode || null);

  const fetched = await fetchAndParse(track.baseUrl, proof.pot, attempts);
  if (fetched === null) {
    return fail(
      'fetch-failed',
      'YouTube did not return a usable caption file. Try the manual paste fallback.',
      { via: pageData.via, availableTracks, pot: proof.via, trackName: track.languageCode },
    );
  }

  const { cues, wordTimingSource } = fetched.parsed;
  const details = getVideoDetails(pageData.playerResponse);
  const lastCueEnd = cues[cues.length - 1]?.end ?? 0;
  const durationSec = getPlayerDuration() ?? details.durationSec ?? lastCueEnd;

  const transcript: Transcript = {
    videoId,
    language: track.languageCode || 'unknown',
    isAutoGenerated: isAutoGenerated(track),
    durationSec: Math.max(durationSec, lastCueEnd),
    cues,
    wordTimingSource,
    source: 'captions',
  };

  const chapters = extractChapters(pageData.ytInitialData);
  if (chapters) transcript.chapters = chapters;

  return {
    ok: true,
    transcript,
    details: {
      via: pageData.via,
      format: fetched.format,
      trackName: track.name?.simpleText ?? track.languageCode ?? null,
      availableTracks,
      pot: proof.via,
      attempts,
    },
  };
}
