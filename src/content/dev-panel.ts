/**
 * Development-only panel for capturing and inspecting transcripts.
 *
 * This exists to build eval/fixtures/. Every later phase develops offline against those
 * files, so they need to be captured accurately and checked against the properties the
 * spec asks for (a fast talker, a slow one with real pauses, one with chapters). The
 * stats readout answers that on the page, before committing anything.
 *
 * A DevTools console helper would not work here: the console evaluates in the page world
 * and cannot reach a content script binding, so this is a button.
 *
 * The whole module is dropped from release builds by the DEV_TOOLS define.
 */

