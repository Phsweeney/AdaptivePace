let current: Transcript | null = null;

function el<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  attributes: Record<string, string> = {},
  children: Array<Node | string> = [],
): HTMLElementTagNameMap[K] {
  const node = document.createElement(tag);
  for (const [key, value] of Object.entries(attributes)) node.setAttribute(key, value);
  node.append(...children);
  return node;
}

function download(name: string, payload: unknown): void {
  const blob = new Blob([`${JSON.stringify(payload, null, 2)}\n`], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const link = el('a', { href: url, download: name });
  document.body.append(link);
  link.click();
  link.remove();
  // Revoke on the next task so the download has already started.
  setTimeout(() => URL.revokeObjectURL(url), 0);
}

function statsList(transcript: Transcript): HTMLElement {
  const stats = computeTranscriptStats(transcript);

  // The flags mark the properties the spec's fixture table asks for, so a candidate video
  // can be accepted or rejected without leaving the page.
  const rows: Array<[string, string, string]> = [
    ['duration', formatDuration(stats.durationSec), stats.durationSec >= 1800 ? 'flag' : ''],
    ['captions', transcript.isAutoGenerated ? 'auto' : 'manual', transcript.isAutoGenerated ? 'flag' : ''],
    ['timings', transcript.wordTimingSource, transcript.wordTimingSource === 'native' ? '' : 'bad'],
    ['cues', String(stats.cueCount), ''],
    ['words', String(stats.wordCount), ''],
    ['avg wpm', stats.avgWpm.toFixed(0), stats.avgWpm > 190 ? 'flag' : ''],
    ['silence', `${stats.silencePct.toFixed(1)}%`, stats.silencePct > 8 ? 'flag' : ''],
    ['chapters', String(stats.chapterCount), stats.chapterCount > 0 ? 'flag' : ''],
    ['language', transcript.language, ''],
  ];

  const list = el('dl');
  for (const [label, value, className] of rows) {
    list.append(el('dt', {}, [label]), el('dd', className ? { class: className } : {}, [value]));
  }
  return list;
}

/** Compact summary of what was tried, shown in the panel when extraction fails. */
function diagnosticsBlock(details: ExtractionDetails): HTMLElement {
  const lines = [
    `page data: ${details.via}`,
    `pot: ${details.pot}`,
    `tracks: ${details.availableTracks.length > 0 ? details.availableTracks.join(', ') : 'none'}`,
    ...details.attempts.map(
      (attempt) => `${attempt.fmt}: ${attempt.status}, ${attempt.bytes} bytes${attempt.parsed ? '' : ', unparsed'}`,
    ),
  ];

  return el('pre', { class: 'diag' }, [lines.join('\n')]);
}

function fixturePayload(transcript: Transcript, details: ExtractionDetails | null): unknown {
  return {
    _meta: {
      capturedAt: new Date().toISOString(),
      sourceUrl: window.location.href,
      via: details?.via ?? 'manual',
      format: details?.format ?? null,
      track: details?.trackName ?? null,
    },
    ...transcript,
  };
}

export function mountDevPanel(): void {
  if (document.getElementById(PANEL_ID)) return;

  const message = el('div', { class: 'msg' }, ['Reading transcript...']);
  const stats = el('div');
  const dumpButton = el('button', { type: 'button', disabled: 'true' }, ['Dump fixture']);
  const reloadButton = el('button', { type: 'button' }, ['Re-read']);
  const pasteArea = el('textarea', { placeholder: 'Paste a transcript to test the fallback' });
  const pasteButton = el('button', { type: 'button' }, ['Parse pasted text']);
  const closeButton = el('button', { type: 'button', title: 'Hide panel' }, ['x']);

  let details: ExtractionDetails | null = null;

  const run = async () => {
    dumpButton.disabled = true;
    stats.replaceChildren();
    message.className = 'msg';
    message.textContent = 'Reading transcript...';

    const result = await extractTranscript();

    // Always log the diagnostics. When extraction fails, this is the only place that says
    // why, and the difference between a refused request and a parser bug matters.
    console.groupCollapsed(`[adaptive playback] extraction ${result.ok ? 'ok' : result.reason}`);
    console.log('page data via:', result.details.via);
    console.log('caption tracks:', result.details.availableTracks);
    if (result.details.attempts.length > 0) console.table(result.details.attempts);
    console.groupEnd();

    if (!result.ok) {
      current = null;
      details = null;
      message.className = 'msg bad';
      message.replaceChildren(result.message, diagnosticsBlock(result.details));
      return;
    }

    current = result.transcript;
    details = result.details;
    stats.replaceChildren(statsList(result.transcript));
    message.className = 'msg';
    message.textContent = `${result.details.format} via ${result.details.via}`;
    dumpButton.disabled = false;
  };

  dumpButton.addEventListener('click', () => {
    if (!current) return;
    download(`${current.videoId || 'transcript'}.json`, fixturePayload(current, details));
  });

  reloadButton.addEventListener('click', () => void run());

  pasteButton.addEventListener('click', () => {
    const videoId = getVideoIdFromUrl() ?? 'pasted';
    const duration = getPlayerDuration();
    const result = parseManualTranscript(
      pasteArea.value,
      duration === null ? { videoId } : { videoId, durationSec: duration },
    );

    if (!result.ok) {
      message.className = 'msg bad';
      message.textContent = result.message;
      return;
    }

    current = result.transcript;
    details = null;
    stats.replaceChildren(statsList(result.transcript));
    message.className = 'msg';
    message.textContent = 'parsed from pasted text';
    dumpButton.disabled = false;
  });

  closeButton.addEventListener('click', () => unmountDevPanel());

  const panel = el('div', { id: PANEL_ID }, [
    el('header', {}, ['adaptive playback', closeButton]),
    el('div', { class: 'body' }, [
      stats,
      message,
      el('div', { class: 'row' }, [dumpButton, reloadButton]),
      pasteArea,
      pasteButton,
    ]),
  ]);

  const style = el('style', { id: `${PANEL_ID}-style` }, [STYLE]);
  document.documentElement.append(style, panel);
  void run();
}

export function unmountDevPanel(): void {
  document.getElementById(PANEL_ID)?.remove();
  document.getElementById(`${PANEL_ID}-style`)?.remove();
  current = null;
}
