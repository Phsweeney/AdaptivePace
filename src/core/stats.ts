/**
 * Descriptive statistics for a Transcript.
 *
 * These exist to make fixture selection a ten second decision. The spec asks for five
 * fixtures with specific properties (a fast talker above 190 wpm, a slow one with more
 * than 8 percent silence), and eyeballing a video cannot answer that. The dev panel shows
 * these numbers on the watch page so a candidate can be accepted or rejected on the spot.
 */

import { countWords } from './text.ts';
import type { Transcript } from './types.ts';

/** Matches the silence gap threshold the chunker uses, so the two agree on what a pause is. */
export const SILENCE_GAP_SEC = 2.0;

export interface TranscriptStats {
  durationSec: number;
  cueCount: number;
  wordCount: number;
  /** Seconds covered by cues. */
  speechSec: number;
  /** Seconds in gaps of at least SILENCE_GAP_SEC, including lead-in and run-out. */
  silenceSec: number;
  silencePct: number;
  /** Words per minute of speech, not per minute of video. */
  avgWpm: number;
  chapterCount: number;
  isAutoGenerated: boolean;
  hasNativeWordTimings: boolean;
}

export function computeTranscriptStats(transcript: Transcript): TranscriptStats {
  const { cues, durationSec } = transcript;

  let wordCount = 0;
  let speechSec = 0;
  let silenceSec = 0;
  let cursor = 0;

  for (const cue of cues) {
    wordCount += countWords(cue.text);
    speechSec += Math.max(cue.end - cue.start, 0);

    const gap = cue.start - cursor;
    if (gap >= SILENCE_GAP_SEC) silenceSec += gap;
    cursor = Math.max(cursor, cue.end);
  }

  const trailingGap = durationSec - cursor;
  if (trailingGap >= SILENCE_GAP_SEC) silenceSec += trailingGap;

  return {
    durationSec,
    cueCount: cues.length,
    wordCount,
    speechSec,
    silenceSec,
    silencePct: durationSec > 0 ? (silenceSec / durationSec) * 100 : 0,
    avgWpm: speechSec > 0 ? wordCount / (speechSec / 60) : 0,
    chapterCount: transcript.chapters?.length ?? 0,
    isAutoGenerated: transcript.isAutoGenerated,
    hasNativeWordTimings: transcript.wordTimingSource === 'native',
  };
}

export function formatDuration(seconds: number): string {
  const total = Math.max(Math.round(seconds), 0);
  const hours = Math.floor(total / 3600);
  const minutes = Math.floor((total % 3600) / 60);
  const secs = total % 60;
  const pad = (value: number) => String(value).padStart(2, '0');
  return hours > 0 ? `${hours}:${pad(minutes)}:${pad(secs)}` : `${minutes}:${pad(secs)}`;
}
