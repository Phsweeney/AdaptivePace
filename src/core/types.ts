// ---------- Output ----------

export interface SpeedSegment {
  start: number;
  end: number;
  speed: number;
  kind: ChunkKind;
  /** Null when alpha is 0 or no scores are available. */
  difficultyZ: number | null;
}

export type Policy = 'fixed' | 'wpm' | 'wpm+llm';

export interface SpeedPlan {
  videoId: string;
  policy: Policy;
  segments: SpeedSegment[];
  meta: {
    originalDurationSec: number;
    estimatedWatchTimeSec: number;
    /** Mean absolute change in ln(speed) per minute of source. */
    whiplash: number;
    scoresImputed: number;
  };
}
