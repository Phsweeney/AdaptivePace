/**
 * Shared types for the extension and the offline eval harness.
 *
 * Nothing in src/core/ may import a browser or chrome.* API. The eval harness imports
 * these modules directly in Node, so a stray DOM reference here breaks it.
 */

// ---------- Transcript ----------

export interface TranscriptWord {
  text: string;
  /** Seconds from video start. */
  start: number;
  end: number;
}

export interface TranscriptCue {
  text: string;
  start: number;
  end: number;
  /** Present for srv3/json3, which carry per-word timing offsets. */
  words?: TranscriptWord[];
}

export interface Chapter {
  title: string;
  start: number;
}

/**
 * Where a transcript's word timings came from.
 *
 * 'native' means the caption format supplied per-word offsets. 'interpolated' means we
 * distributed cue duration across the words ourselves. Downstream code cannot tell the
 * two apart by looking at the words, so the distinction is recorded here: interpolated
 * timings make nativeWpm a per-cue average rather than a real measurement.
 */
export type WordTimingSource = 'native' | 'interpolated';

/** Captions pulled from the page, or text the user pasted in by hand. */
export type TranscriptSource = 'captions' | 'manual';

export interface Transcript {
  videoId: string;
  language: string;
  isAutoGenerated: boolean;
  durationSec: number;
  cues: TranscriptCue[];
  chapters?: Chapter[];
  wordTimingSource: WordTimingSource;
  source: TranscriptSource;
}

// ---------- Extraction results ----------

export type TranscriptFailureReason =
  | 'not-a-watch-page'
  | 'no-player-response'
  | 'no-captions'
  | 'fetch-failed'
  | 'parse-failed';

export interface TranscriptFailure {
  ok: false;
  reason: TranscriptFailureReason;
  /** Safe to show in the UI as-is. */
  message: string;
}

export interface TranscriptSuccess {
  ok: true;
  transcript: Transcript;
}

/**
 * Extraction always resolves, never throws. A video without captions is an ordinary
 * outcome, not an exceptional one.
 */
export type TranscriptResult = TranscriptSuccess | TranscriptFailure;

export function transcriptFailure(
  reason: TranscriptFailureReason,
  message: string,
): TranscriptFailure {
  return { ok: false, reason, message };
}

// ---------- Chunking ----------

export type ChunkKind = 'speech' | 'silence';

export interface Chunk {
  /** Dense and 0-indexed across all chunks including silence, stable within a Transcript. */
  id: number;
  kind: ChunkKind;
  start: number;
  end: number;
  /** Empty string for silence. */
  text: string;
  wordCount: number;
  /** 0 for silence. */
  nativeWpm: number;
}

// ---------- Difficulty ----------

export interface DifficultyScore {
  chunkId: number;
  /** 1-10 as returned by the model. */
  raw: number;
  /** z-scored across all speech chunks. */
  z: number;
  /** True if interpolated after a missing model output. */
  imputed: boolean;
}

// ---------- Settings ----------

export interface Settings {
  // Provider
  baseUrl: string;
  apiKey: string;
  model: string;

  // Pacing
  /** R, the target effective word rate in wpm. */
  targetWpm: number;
  minSpeed: number;
  maxSpeed: number;
  /** Difficulty weight, 0-1. The only trust knob. */
  alpha: number;
  silenceSpeed: number;

  // Shaping
  smoothingWindowSec: number;
  minDwellSec: number;
  /** Rounding granularity for the final speed. */
  speedStep: number;

  // Limits
  maxVideoDurationMin: number;
  enabled: boolean;
}

