/**
 * The options page.
 *
 * Two things here are deliberate rather than incidental.
 *
 * Nobody thinks in words per minute, so the pace control is a slider labelled Relaxed to
 * Brisk, and what it reports is the outcome: how long a real lecture would take at that
 * setting. That number is produced by running the actual pacing engine over a real chunk
 * profile, not by a formula written to look plausible. If the engine changes, this readout
 * changes with it, which is the point.
 *
 * Settings save as you change them and the content script re-plans live, so a slider shows
 * its effect on the video you are watching without a save button or a reload.
 */

import { computeSpeedPlan } from '../core/pacing.ts';
import { formatDuration } from '../core/stats.ts';
import { DEFAULTS } from '../core/types.ts';
import type { Settings, Transcript } from '../core/types.ts';
import { loadSettings, saveSettings } from '../storage/settings.ts';
import { REFERENCE_DURATION_SEC, referenceChunks } from './reference-profile.ts';

type NumericField = Extract<
  keyof Settings,
  'targetWpm' | 'minSpeed' | 'maxSpeed' | 'alpha' | 'silenceSpeed' | 'maxVideoDurationMin'
>;
type TextField = Extract<keyof Settings, 'baseUrl' | 'model' | 'apiKey'>;

const NUMERIC_FIELDS: NumericField[] = [
  'targetWpm',
  'minSpeed',
  'maxSpeed',
  'alpha',
  'silenceSpeed',
  'maxVideoDurationMin',
];
const TEXT_FIELDS: TextField[] = ['baseUrl', 'model', 'apiKey'];

const CHUNKS = referenceChunks();
/** Only the fields the planner reads; the chunks are supplied separately. */
const REFERENCE_TRANSCRIPT: Transcript = {
  videoId: 'reference',
  language: 'en',
  isAutoGenerated: false,
  durationSec: REFERENCE_DURATION_SEC,
  cues: [],
  wordTimingSource: 'interpolated',
  source: 'captions',
};

function input(id: string): HTMLInputElement {
  const element = document.getElementById(id);
  if (!(element instanceof HTMLInputElement)) throw new Error(`missing input #${id}`);
  return element;
}

function text(id: string): HTMLElement {
  const element = document.getElementById(id);
  if (element === null) throw new Error(`missing element #${id}`);
  return element;
}

/** Runs the real engine over the reference lecture and describes the outcome in minutes. */
function describePace(settings: Settings): string {
  const plan = computeSpeedPlan(REFERENCE_TRANSCRIPT, CHUNKS, null, settings);
  const original = formatDuration(plan.meta.originalDurationSec);
  const watched = formatDuration(plan.meta.estimatedWatchTimeSec);
  const saved = Math.round(
    (1 - plan.meta.estimatedWatchTimeSec / plan.meta.originalDurationSec) * 100,
  );

  if (saved <= 0) return `A ${original} lecture would still take about ${watched}.`;
  return `A ${original} lecture would take about ${watched}, saving ${saved} percent.`;
}

function describeAlpha(settings: Settings): string {
  if (settings.alpha === 0) {
    return 'Off. Speed comes only from how fast the speaker is talking, and no transcript is sent anywhere.';
  }
  return 'Harder passages are slowed below the pace above, easier ones sped up. Requires a model provider, which this build does not use yet.';
}

async function main(): Promise<void> {
  const settings = await loadSettings();
  const paceReadout = text('paceReadout');
  const alphaHint = text('alphaHint');
  const saved = text('saved');

  const enabled = input('enabled');
  enabled.checked = settings.enabled;

  for (const field of NUMERIC_FIELDS) input(field).value = String(settings[field]);
  for (const field of TEXT_FIELDS) input(field).value = settings[field];

  const refreshDerived = () => {
    paceReadout.textContent = describePace(settings);
    alphaHint.textContent = describeAlpha(settings);
  };
  refreshDerived();

  let savedTimer: ReturnType<typeof setTimeout> | undefined;
  const commit = (partial: Partial<Settings>) => {
    Object.assign(settings, partial);
    refreshDerived();
    void saveSettings(partial);

    saved.textContent = 'Saved';
    clearTimeout(savedTimer);
    savedTimer = setTimeout(() => {
      saved.textContent = '';
    }, 1200);
  };

  enabled.addEventListener('change', () => commit({ enabled: enabled.checked }));

  for (const field of NUMERIC_FIELDS) {
    const element = input(field);
    element.addEventListener('input', () => {
      const value = Number(element.value);
      // An empty or half-typed number field must not be written through as NaN, which would
      // reach the pacing math and produce a plan full of holes.
      if (!Number.isFinite(value)) return;
      commit({ [field]: value } as Partial<Settings>);
    });
  }

  for (const field of TEXT_FIELDS) {
    const element = input(field);
    element.addEventListener('input', () => commit({ [field]: element.value } as Partial<Settings>));
  }

  const apiKey = input('apiKey');
  const reveal = document.getElementById('revealKey');
  reveal?.addEventListener('click', () => {
    const hidden = apiKey.type === 'password';
    apiKey.type = hidden ? 'text' : 'password';
    reveal.textContent = hidden ? 'Hide' : 'Show';
  });
}

void main().catch(() => {
  const saved = document.getElementById('saved');
  if (saved) saved.textContent = `Could not load settings. Using defaults (${DEFAULTS.targetWpm} wpm).`;
});
